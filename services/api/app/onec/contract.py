"""Контракт обмена с 1С.

Всё, что знает о 1С остальное приложение, описано здесь. За этим портом
стоят две реализации — эмулятор и настоящий OData-клиент, — и переключение
между ними не меняет ни строчки в заявках и витринах.

Формы намеренно свои, а не «как в 1С»: нормализация на границе означает,
что второй транспорт (HTTP-сервисы, CommerceML) подключается как ещё одна
реализация этого же порта.
"""

from __future__ import annotations

from dataclasses import dataclass, field
from typing import Protocol


class OneCUnavailable(Exception):
    """1С недоступна или ответила отказом.

    Отдельный тип нужен ради правила продукта: недоступность 1С не роняет
    основной сценарий, заявка подтверждается и уходит в очередь.
    """


@dataclass(frozen=True)
class CatalogItem:
    """Позиция номенклатуры вместе с ценой и остатком."""
    # Артикул (код) — то, что поставщик видит в прайсе.
    external_id: str
    name: str
    unit: str = "шт"
    # Кратности в типовой УТ нет: None — оставить ту, что задал поставщик.
    pack_size: float | None = None
    price: float = 0
    stock: float = 0
    # Ссылка на позицию в 1С (GUID): документы ссылаются только ею.
    ref: str = ""


@dataclass(frozen=True)
class DocumentLine:
    # Ссылка на номенклатуру в 1С (GUID).
    ref: str
    name: str
    qty: float
    price: float


@dataclass(frozen=True)
class Document:
    """«Заказ клиента» на выгрузку."""
    external_key: str
    client: str
    comment: str = ""
    lines: list[DocumentLine] = field(default_factory=list)
    # Статус заказа: «НеСогласован» — клиент оформил, поставщик ещё не
    # подтвердил; рабочий («КВыполнению») — подтверждён. Пусто — как решит база.
    status: str = ""
    # Дата доставки, ГГГГ-ММ-ДД. В «Заказе клиента» УТ это «Дата отгрузки»:
    # поставщик переносит доставку — меняется и она.
    ship_date: str = ""
    # Провести после записи: проведённый в рабочем статусе заказ
    # резервирует товар, «На согласовании» не проводим.
    post: bool = False
    # Реквизиты заказа ссылками 1С: организация, склад, валюта, партнёр,
    # контрагент, соглашение — см. settings.py.
    refs: dict[str, str] = field(default_factory=dict)


class OneC(Protocol):
    """Порт обмена. Реализации: simulated, odata."""

    name: str

    async def catalog(self) -> list[CatalogItem]:
        """Номенклатура с ценами и остатками."""

    async def push_order(self, document: Document) -> str:
        """Создаёт «Заказ клиента», возвращает номер документа.

        Идемпотентность на стороне реализации: повторный вызов с тем же
        `external_key` обязан вернуть номер уже созданного документа.
        """

    async def note_order(self, external_key: str, text: str) -> str | None:
        """Дописывает к «Заказу клиента» комментарий — расхождения приёмки.

        Корректировку в УТ оформляют по реализации, а не по заказу, и
        реализацию создаёт учётчик: приложение передаёт ему расхождения,
        а не выдумывает документ. Заказа нет — None."""

    async def update_order(self, document: Document) -> str:
        """Меняет состав и статус «Заказа клиента» с тем же `external_key` и
        перепроводит его: резерв встаёт по новым количествам. Документа нет —
        создаёт. Возвращает номер."""

    async def cancel_order(self, external_key: str, comment: str) -> str | None:
        """Отменяет проведение заказа и ставит пометку удаления: резерв
        возвращается на склад. Документа нет — None."""
