"""Возвращает тестовую базу «Демо» к исходной номенклатуре и остаткам.

Заказы теперь честно списывают остаток, и после десятка репетиций склад
демо-базы пустеет. Сброс стенда трогает только её: базы, заведённые в
кабинете, остаются как есть. Запускается при сбросе демо-стенда, после
него эмулятор перезапускают — иначе работающий процесс перезапишет файл
своим состоянием.
"""

from store import Store, _seed_items

store = Store()
demo = store.base("demo")
if demo is not None:
    demo["items"] = _seed_items()
    for bucket in ("documents", "corrections", "writeoffs"):
        demo[bucket] = []
    store.commit()
    print(f"демо-база сброшена: позиций {len(demo['items'])}")
